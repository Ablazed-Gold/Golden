const { chromium } = require("playwright");
const path = require("path");
const URL = "file:///" + path.resolve(__dirname, "../../index.html").replace(/\\\\/g, "/");
(async () => {
  const b = await chromium.launch();
  const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
  await p.goto(URL, { waitUntil: "load" });
  await p.waitForTimeout(4700);
  await p.evaluate(() => window.scrollTo(0, document.getElementById("fab").offsetTop - 120));
  await p.waitForSelector("#fab-cinema.is-on", { timeout: 9000 });
  await p.waitForTimeout(150);
  await p.screenshot({ path: path.resolve(__dirname, "../../preview/cinema-curtain.png") });
  await p.waitForSelector("#fab-cinema.is-title", { timeout: 5000 });
  await p.waitForTimeout(900);
  await p.screenshot({ path: path.resolve(__dirname, "../../preview/cinema-title.png") });
  await p.waitForSelector("#fab-cinema.is-printing", { timeout: 6000 });
  await p.waitForTimeout(2200);
  await p.screenshot({ path: path.resolve(__dirname, "../../preview/cinema-print.png") });
  await p.waitForSelector("#fab-cinema.is-shenzhen", { timeout: 9000 });
  await p.waitForTimeout(900);
  await p.screenshot({ path: path.resolve(__dirname, "../../preview/cinema-shenzhen-mid.png") });
  await p.waitForTimeout(900);
  await p.screenshot({ path: path.resolve(__dirname, "../../preview/cinema-shenzhen.png") });
  await p.waitForFunction(() => document.getElementById("fab-cinema").hidden === true, null, { timeout: 9000 });
  await p.waitForTimeout(700);
  await p.screenshot({ path: path.resolve(__dirname, "../../preview/fab.png") });
  await p.evaluate(() => window.scrollTo(0, 0));
  await p.waitForTimeout(1000);
  await p.screenshot({ path: path.resolve(__dirname, "../../preview/full.png"), fullPage: true });
  console.log("previews ok");
  await b.close();
})();
