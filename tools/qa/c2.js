const { chromium } = require("playwright");
const path = require("path");
const URL = "file:///" + path.resolve(__dirname, "../../index.html").replace(/\\\\/g, "/");
(async () => {
  const b = await chromium.launch();
  const out = { errors: [] };
  const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
  p.on("pageerror", e => out.errors.push(e.message));
  p.on("console", m => { if (m.type() === "error") out.errors.push(m.text()); });
  await p.goto(URL, { waitUntil: "load" });
  await p.waitForTimeout(4700);
  await p.evaluate(() => window.scrollTo(0, document.getElementById("fab").offsetTop - 200));
  await p.waitForSelector("#fab-cinema.is-on", { timeout: 7000 });
  await p.waitForTimeout(140);
  await p.screenshot({ path: "shots/c2-curtain.png" });
  await p.waitForSelector("#fab-cinema.is-title", { timeout: 4000 });
  await p.waitForTimeout(300);
  await p.screenshot({ path: "shots/c2-title.png" });
  await p.waitForSelector("#fab-cinema.is-intro", { timeout: 3000 });
  await p.waitForTimeout(500);
  await p.screenshot({ path: "shots/c2-intro.png" });
  await p.waitForSelector("#fab-cinema.is-printing", { timeout: 4000 });
  await p.waitForTimeout(2400);
  await p.screenshot({ path: "shots/c2-print.png" });
  await p.waitForSelector("#fab-cinema.is-shenzhen", { timeout: 10000 });
  await p.waitForTimeout(420);
  await p.screenshot({ path: "shots/c2-shenzhen-mid.png" });
  await p.waitForTimeout(1000);
  await p.screenshot({ path: "shots/c2-shenzhen.png" });
  out.shenzhen = await p.evaluate(() => ({ layer: document.getElementById("cinema-layer").textContent, cityText: document.getElementById("cinema-city").textContent, cityOpacity: getComputedStyle(document.getElementById("cinema-city")).opacity }));
  await p.waitForFunction(() => document.getElementById("fab-cinema").hidden === true, null, { timeout: 8000 });
  await p.waitForTimeout(700);
  await p.screenshot({ path: "shots/c2-final.png" });
  out.final = await p.evaluate(() => ({ canvasParent: document.getElementById("city-canvas").parentElement.id, theater: document.getElementById("fab").className, bg: getComputedStyle(document.getElementById("fab-city-bg")).opacity, overflow: document.documentElement.scrollWidth - innerWidth, fabTop: Math.round(document.getElementById("fab").getBoundingClientRect().top), scrollY: Math.round(window.scrollY) }));
  console.log(JSON.stringify(out, null, 2));
  await b.close();
})();
